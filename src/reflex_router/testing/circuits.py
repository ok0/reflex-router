"""Synthetic circuits, no FlyWire data: builders for tests and measurement fixtures only.

The demo mapping is test scaffolding, not the project default mapping (the encoder comes in M9).
"""

from collections.abc import Sequence
from os import PathLike

import numpy as np

from reflex_router.circuit import (
    SHIU_PARAMS,
    Circuit,
    CircuitSpec,
    LIFParams,
    Neuron,
    Provenance,
    Role,
    Stimulus,
    load_circuit,
    write_circuit,
)
from reflex_router.gate.base import GateInput

SYNTHETIC_PROVENANCE = Provenance(
    data_version="synthetic",
    license="MIT (synthetic test circuit, no FlyWire data)",
    notes="synthetic circuit generated by reflex_router.testing.circuits",
)

DEMO_LC4_HZ = 50.0
DEMO_LPLC2_MAX_HZ = 150.0


def build_spec(
    neurons: Sequence[tuple[int, Role, int]],
    connections: Sequence[tuple[int, int, int]],
    params: LIFParams = SHIU_PARAMS,
) -> CircuitSpec:
    return CircuitSpec(
        neurons=tuple(
            Neuron(root_id=root_id, role=role, sign=sign, cell_type="synthetic", side="na")
            for root_id, role, sign in neurons
        ),
        connections=tuple(connections),
        params=params,
    )


def write_and_load(directory: str | PathLike[str], spec: CircuitSpec) -> Circuit:
    write_circuit(directory, spec, SYNTHETIC_PROVENANCE)
    return load_circuit(directory)


def demo_race_spec() -> CircuitSpec:
    neurons: list[tuple[int, Role, int]] = [
        (1, "input_lc4", 1),
        *[(11 + i, "input_lplc2", 1) for i in range(10)],
        (100, "output_gf", 1),
        (200, "output_parallel", 1),
        (300, "inter", 1),
    ]
    connections: list[tuple[int, int, int]] = [
        *[(11 + i, 100, 30) for i in range(10)],
        (1, 300, 200),
        (300, 200, 200),
    ]
    return build_spec(neurons, connections)


def demo_mapping(x: GateInput) -> Stimulus:
    return Stimulus(DEMO_LC4_HZ, DEMO_LPLC2_MAX_HZ * min(max(x.evidence, 0.0), 1.0))


def random_spec(
    n_neurons: int,
    *,
    seed: int = 0,
    n_lc4: int = 50,
    n_lplc2: int = 50,
    n_parallel: int = 4,
    out_degree: int = 10,
    max_count: int = 20,
    inhibitory_fraction: float = 0.2,
) -> CircuitSpec:
    if n_neurons < n_lc4 + n_lplc2 + 1 + n_parallel + 1:
        raise ValueError(
            f"n_neurons={n_neurons} too small for {n_lc4} lc4, {n_lplc2} lplc2, "
            f"1 gf, {n_parallel} parallel and at least one inter neuron"
        )
    rng = np.random.default_rng(seed)
    n_inputs = n_lc4 + n_lplc2
    n_gf_end = n_inputs + 1
    n_par_end = n_gf_end + n_parallel

    roles: dict[int, Role] = {}
    neurons: list[tuple[int, Role, int]] = []
    for root_id in range(1, n_neurons + 1):
        k = root_id - 1
        if k < n_lc4:
            role: Role = "input_lc4"
        elif k < n_inputs:
            role = "input_lplc2"
        elif k < n_gf_end:
            role = "output_gf"
        elif k < n_par_end:
            role = "output_parallel"
        else:
            role = "inter"
        roles[root_id] = role
        if role.startswith("input_"):
            sign = 1
        else:
            sign = -1 if rng.random() < inhibitory_fraction else 1
        neurons.append((root_id, role, sign))

    non_input = np.array(
        [r for r in range(1, n_neurons + 1) if not roles[r].startswith("input_")], dtype=np.int64
    )
    connections: list[tuple[int, int, int]] = []
    for pre in range(1, n_neurons + 1):
        cands = non_input[non_input != pre]
        k = min(out_degree, int(cands.size))
        targets = rng.choice(cands, size=k, replace=False)
        counts = rng.integers(1, max_count + 1, size=k)
        for post, count in zip(targets.tolist(), counts.tolist(), strict=True):
            connections.append((pre, int(post), int(count)))
    return build_spec(neurons, connections)
